const norm = (s: string) => s.toLowerCase().replace(/\s+/g, " ").trim()

// Matches a subscription's free-text description to a known service, on whole
// words only so "max" doesn't match "maximum". Longest alias wins.
export function findService(text?: string | null): Service | null {
  if (!text) return null
  const t = " " + norm(text).replace(/[^a-z0-9+.]+/g, " ") + " "
  let best: { service: Service; len: number } | null = null
  for (const service of SERVICES) {
    for (const alias of service.aliases) {
      const a = " " + norm(alias) + " "
      if (t.includes(a) && (!best || alias.length > best.len)) best = { service, len: alias.length }
    }
  }
  return best?.service ?? null
}
